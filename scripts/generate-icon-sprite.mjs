#!/usr/bin/env node
/**
 * Builds public/icons.svg from the Lucide icons this app uses.
 * Inline SVGs were the bulk of every page's HTML. A sprite keeps the glyph
 * and leaves one short <use> tag in the document.
 * Run: node scripts/generate-icon-sprite.mjs
 */
import { readFileSync, writeFileSync, readdirSync } from "fs";
import { join, dirname } from "path";
import { fileURLToPath, pathToFileURL } from "url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const iconDir = join(root, "node_modules/lucide-react/dist/esm/icons");

const FILE_OVERRIDE = {
  Fingerprint: "fingerprint-pattern",
};

function kebab(name) {
  return (
    FILE_OVERRIDE[name] ??
    name
      .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
      .replace(/([A-Z]+)([A-Z][a-z])/g, "$1-$2")
      .replace(/([a-zA-Z])(\d)/g, "$1-$2")
      .toLowerCase()
  );
}

function collectNames() {
  const names = new Set(["Wrench"]);
  const iconSrc = readFileSync(join(root, "src/components/ui/Icon.tsx"), "utf8");
  for (const m of iconSrc.matchAll(/^  ([A-Z][A-Za-z0-9]+),$/gm)) names.add(m[1]);
  const sprite = join(root, "public/icons.svg");
  try {
    const svg = readFileSync(sprite, "utf8");
    for (const m of svg.matchAll(/id="([A-Z][A-Za-z0-9]+)"/g)) names.add(m[1]);
  } catch {
    /* first run */
  }
  const map = readFileSync(join(root, "src/lib/catalog/tool-icon-map.generated.ts"), "utf8");
  for (const m of map.matchAll(/: "([A-Z][A-Za-z0-9]+)"/g)) names.add(m[1]);
  return [...names];
}

function attrName(key) {
  return key.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
}

function renderNode([tag, attrs]) {
  const parts = [];
  for (const [key, value] of Object.entries(attrs)) {
    if (key === "key") continue;
    parts.push(`${attrName(key)}="${String(value).replace(/"/g, "&quot;")}"`);
  }
  return `<${tag} ${parts.join(" ")}/>`;
}

const files = new Set(readdirSync(iconDir).filter((f) => f.endsWith(".mjs") && !f.includes(".map")));

function resolveFile(start) {
  let file = start;
  const seen = new Set();
  while (!seen.has(file)) {
    seen.add(file);
    if (!files.has(file)) return null;
    const src = readFileSync(join(iconDir, file), "utf8");
    const reexport = src.match(/export \{ default \} from '\.\/([^']+)'/);
    if (!reexport) return file;
    file = reexport[1];
  }
  return null;
}

const symbols = [];
const missing = [];

for (const name of collectNames()) {
  const file = resolveFile(`${kebab(name)}.mjs`);
  if (!file) {
    missing.push(`${name} → ${kebab(name)}.mjs`);
    continue;
  }
  const mod = await import(pathToFileURL(join(iconDir, file)).href);
  const nodes = mod.__iconNode;
  if (!nodes) {
    missing.push(name);
    continue;
  }
  symbols.push(
    `  <symbol id="${name}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${nodes.map(renderNode).join("")}</symbol>`,
  );
}

if (missing.length) {
  console.error("Missing Lucide icons:\n" + missing.join("\n"));
  process.exit(1);
}

const svg = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Icons from Lucide (ISC). Generated by scripts/generate-icon-sprite.mjs -->
<svg xmlns="http://www.w3.org/2000/svg">
${symbols.join("\n")}
</svg>
`;

writeFileSync(join(root, "public/icons.svg"), svg);
console.log(`✓ ${symbols.length} icons → public/icons.svg (${svg.length} bytes)`);
